export interface Template {
  id: string
  name: string
  category: string
  tags: string[]
  width: number
  height: number
  design: Design
}

function buildTemplate(def: TemplateDef): Template {
  const elements = LAYOUTS[def.layout](def.width, def.height, def.theme)
  const design: Design = {
    id: `tpl_${def.id}`,
    title: def.name,
    width: def.width,
    height: def.height,
    pages: [{ id: uid('page'), background: def.theme.bg, elements }],
    createdAt: 0,
    updatedAt: 0,
    templateId: def.id,
  }
  return {
    id: def.id,
    name: def.name,
    category: def.category,
    tags: def.tags,
    width: def.width,
    height: def.height,
    design,
  }
}

export const TEMPLATES: Template[] = DEFS.map(buildTemplate)

export function templateById(id: string): Template | undefined {
  return TEMPLATES.find((t) => t.id === id)
}

export function designFromTemplate(template: Template, title?: string): Design {
  const now = Date.now()
  return {
    id: uid('dsn'),
    title: title ?? template.name,
    width: template.width,
    height: template.height,
    pages: clonePages(template.design.pages),
    createdAt: now,
    updatedAt: now,
    templateId: template.id,
  }
}
