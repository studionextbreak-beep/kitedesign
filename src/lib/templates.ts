const splitPhoto: Layout = (w, h, t) => {
  const p = pad(w)
  const stacked = h > w * 1.15
  const photoBox = stacked
    ? { x: 0, y: 0, w, h: h * 0.46 }
    : { x: w * 0.52, y: 0, w: w * 0.48, h }
  const textW = stacked ? w - p * 2 : w * 0.42
  const textY = stacked ? h * 0.53 : h * 0.22
  const elements: DesignElement[] = [
    newShape({ ...photoBox, shape: 'rect', fill: t.accent, name: 'Photo plate' }),
    newImage({ ...photoBox, src: photoUrl(t.photo ?? 'studio', photoBox.w, photoBox.h), name: 'Photo' }),
  ]
  elements.push(
    newText({
      text: t.kicker ?? '',
      x: p,
      y: stacked ? textY : h * 0.14,
      w: textW,
      h: w * 0.05,
      fontSize: Math.round(w * 0.018),
      fontWeight: 600,
      fontFamily: t.body,
      color: t.accent,
      letterSpacing: 0.24,
      uppercase: true,
      lineHeight: 1,
      name: 'Kicker',
    }),
    newText({
      text: t.title,
      x: p,
      y: (stacked ? textY : h * 0.14) + w * 0.055,
      w: textW,
      h: h * 0.28,
      fontSize: Math.round(w * (stacked ? 0.085 : 0.062)),
      fontWeight: 700,
      fontFamily: t.display,
      color: t.ink,
      lineHeight: 1.02,
      letterSpacing: -0.02,
      name: 'Headline',
    }),
    newText({
      text: t.sub ?? '',
      x: p,
      y: stacked ? h * 0.8 : h * 0.55,
      w: textW,
      h: h * 0.12,
      fontSize: Math.round(w * 0.024),
      fontWeight: 400,
      fontFamily: t.body,
      color: t.ink,
      opacity: 0.78,
      lineHeight: 1.45,
      name: 'Subheading',
    }),
  )
  if (t.cta) {
    const pillW = Math.round(w * 0.26)
    const pillH = Math.round(w * 0.062)
    const pillY = stacked ? h * 0.93 - pillH : h * 0.74
    elements.push(
      newShape({ shape: 'rect', x: p, y: pillY, w: pillW, h: pillH, radius: 999, fill: t.ink, name: 'Button' }),
      newText({
        text: t.cta,
        x: p,
        y: pillY + pillH * 0.3,
        w: pillW,
        h: pillH,
        fontSize: Math.round(w * 0.02),
        fontWeight: 600,
        fontFamily: t.body,
        color: t.bg,
        align: 'center',
        lineHeight: 1,
        name: 'Button label',
      }),
    )
  }
  return elements
}

